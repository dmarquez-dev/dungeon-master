namespace DungeonMaster.Domain.Entities.Floors;

/// <summary>
///		Identifies the direction in which a placed object's rotation is stepped.
/// </summary>
public enum RotationDirection
{
	/// <summary>
	///		Rotates the object clockwise.
	/// </summary>
	Clockwise,

	/// <summary>
	///		Rotates the object counter-clockwise.
	/// </summary>
	CounterClockwise
}
